-- 1. EXTENSÕES
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. TABELA DE CATEGORIAS
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABELA DE PRODUTOS
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT,
    cost_price NUMERIC(10, 2) DEFAULT 0.00 NOT NULL,
    sale_price NUMERIC(10, 2) NOT NULL,
    stock_quantity INTEGER DEFAULT 0 NOT NULL,
    min_stock INTEGER DEFAULT 5 NOT NULL,
    unit TEXT DEFAULT 'un' NOT NULL,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. TABELA DE TURNOS DE CAIXA (ABERTURA E FECHAMENTO)
CREATE TABLE IF NOT EXISTS public.cash_shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    opened_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    closed_at TIMESTAMP WITH TIME ZONE,
    initial_amount NUMERIC(10, 2) DEFAULT 0.00 NOT NULL,
    final_amount NUMERIC(10, 2),        -- Valor informado na contagem física da gaveta
    system_amount NUMERIC(10, 2),       -- Valor calculado pelo sistema
    difference NUMERIC(10, 2),          -- Sobra (+) ou Falta (-)
    status TEXT DEFAULT 'OPEN' NOT NULL, -- 'OPEN' ou 'CLOSED'
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. TABELA DE TRANSAÇÕES DE CAIXA (SANGRIAS E SUPRIMENTOS)
CREATE TABLE IF NOT EXISTS public.cash_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT REFERENCES public.cash_shifts(id) ON DELETE CASCADE NOT NULL,
    type TEXT NOT NULL,                  -- 'SANGRIA' (Retirada) ou 'SUPRIMENTO' (Entrada de Troco)
    amount NUMERIC(10, 2) NOT NULL,
    reason TEXT NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. TABELA DE COMPRAS (SUPRIMENTOS / ENTRADAS)
CREATE TABLE IF NOT EXISTS public.purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL,
    supplier TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. ITENS DA COMPRA
CREATE TABLE IF NOT EXISTS public.purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT REFERENCES public.purchases(id) ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE RESTRICT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_cost NUMERIC(10, 2) NOT NULL
);

-- 8. TABELA DE VENDAS
CREATE TABLE IF NOT EXISTS public.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL,
    discount_amount NUMERIC(10, 2) DEFAULT 0.00 NOT NULL,
    payment_method TEXT NOT NULL, -- 'Dinheiro', 'Pix', 'Crédito', 'Débito'
    status TEXT DEFAULT 'COMPLETED' NOT NULL, -- 'COMPLETED' ou 'CANCELED'
    shift_id BIGINT REFERENCES public.cash_shifts(id) ON DELETE SET NULL,
    cancel_reason TEXT,
    canceled_at TIMESTAMP WITH TIME ZONE,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 9. ITENS DA VENDA
CREATE TABLE IF NOT EXISTS public.sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT REFERENCES public.sales(id) ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE RESTRICT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL
);

-- 10. TABELA DE MOVIMENTAÇÕES DE ESTOQUE
CREATE TABLE IF NOT EXISTS public.stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE NOT NULL,
    movement_type TEXT NOT NULL, -- 'IN' ou 'OUT'
    quantity INTEGER NOT NULL,
    origin TEXT NOT NULL,        -- 'SALE', 'PURCHASE', 'MANUAL', 'SALE_CANCEL'
    note TEXT,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 11. TABELA DE PERFIS DE USUÁRIOS
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT,
    full_name TEXT,
    role TEXT DEFAULT 'operator' NOT NULL, -- 'admin' ou 'operator'
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 12. TRIGGER DE CRIAÇÃO AUTOMÁTICA DE PERFIL NO CADASTRO
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, full_name, role)
    VALUES (
        new.id,
        new.email,
        COALESCE(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
        COALESCE(new.raw_user_meta_data->>'role', 'admin')
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- 13. FUNÇÃO RPC: FINALIZAR VENDA (COM BAIXA ATÔMICA, DESCONTO E CAIXA)
CREATE OR REPLACE FUNCTION public.create_complete_sale(
    p_payment_method TEXT,
    p_items JSONB,
    p_user_id UUID DEFAULT NULL,
    p_discount_amount NUMERIC DEFAULT 0.00,
    p_shift_id BIGINT DEFAULT NULL
)
RETURNS JSONB AS $$
DECLARE
    v_sale_id BIGINT;
    v_gross_amount NUMERIC(10, 2) := 0;
    v_net_amount NUMERIC(10, 2) := 0;
    v_item JSONB;
    v_product RECORD;
    v_qty INTEGER;
    v_price NUMERIC(10, 2);
BEGIN
    -- 1. Validar estoque e somar valor bruto
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_qty := (v_item->>'quantity')::INTEGER;
        
        SELECT id, name, sale_price, stock_quantity, is_active
        INTO v_product
        FROM public.products
        WHERE id = (v_item->>'product_id')::BIGINT;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Produto ID % não encontrado.', (v_item->>'product_id');
        END IF;

        IF NOT v_product.is_active THEN
            RAISE EXCEPTION 'O produto "%" está inativo.', v_product.name;
        END IF;

        IF v_product.stock_quantity < v_qty THEN
            RAISE EXCEPTION 'Estoque insuficiente para "%". Disponível: %, Solicitado: %', 
                v_product.name, v_product.stock_quantity, v_qty;
        END IF;

        v_price := v_product.sale_price;
        v_gross_amount := v_gross_amount + (v_qty * v_price);
    END LOOP;

    -- Aplicar desconto
    v_net_amount := GREATEST(0.00, v_gross_amount - COALESCE(p_discount_amount, 0.00));

    -- 2. Criar registro da venda com desconto e turno de caixa
    INSERT INTO public.sales (total_amount, discount_amount, payment_method, user_id, shift_id, status)
    VALUES (v_net_amount, COALESCE(p_discount_amount, 0.00), p_payment_method, p_user_id, p_shift_id, 'COMPLETED')
    RETURNING id INTO v_sale_id;

    -- 3. Inserir itens e decrementar estoque
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_qty := (v_item->>'quantity')::INTEGER;

        SELECT sale_price INTO v_price
        FROM public.products
        WHERE id = (v_item->>'product_id')::BIGINT;

        INSERT INTO public.sale_items (sale_id, product_id, quantity, unit_price)
        VALUES (v_sale_id, (v_item->>'product_id')::BIGINT, v_qty, v_price);

        UPDATE public.products
        SET stock_quantity = stock_quantity - v_qty,
            updated_at = timezone('utc'::text, now())
        WHERE id = (v_item->>'product_id')::BIGINT;

        INSERT INTO public.stock_movements (product_id, movement_type, quantity, origin, note, user_id)
        VALUES (
            (v_item->>'product_id')::BIGINT,
            'OUT',
            v_qty,
            'SALE',
            'Venda #' || v_sale_id,
            p_user_id
        );
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'sale_id', v_sale_id,
        'gross_amount', v_gross_amount,
        'discount_amount', COALESCE(p_discount_amount, 0.00),
        'total_amount', v_net_amount
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 14. FUNÇÃO RPC: CANCELAR VENDA E ESTORNAR ESTOQUE
CREATE OR REPLACE FUNCTION public.cancel_sale(
    p_sale_id BIGINT,
    p_reason TEXT,
    p_user_id UUID DEFAULT NULL
)
RETURNS JSONB AS $$
DECLARE
    v_sale RECORD;
    v_item RECORD;
BEGIN
    SELECT * INTO v_sale FROM public.sales WHERE id = p_sale_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Venda #% não encontrada.', p_sale_id;
    END IF;

    IF v_sale.status = 'CANCELED' THEN
        RAISE EXCEPTION 'A venda #% já foi cancelada anteriormente.', p_sale_id;
    END IF;

    UPDATE public.sales
    SET status = 'CANCELED',
        cancel_reason = p_reason,
        canceled_at = timezone('utc'::text, now())
    WHERE id = p_sale_id;

    FOR v_item IN SELECT * FROM public.sale_items WHERE sale_id = p_sale_id
    LOOP
        UPDATE public.products
        SET stock_quantity = stock_quantity + v_item.quantity,
            updated_at = timezone('utc'::text, now())
        WHERE id = v_item.product_id;

        INSERT INTO public.stock_movements (product_id, movement_type, quantity, origin, note, user_id)
        VALUES (
            v_item.product_id,
            'IN',
            v_item.quantity,
            'SALE_CANCEL',
            'Estorno da Venda #' || p_sale_id || ' - Motivo: ' || COALESCE(p_reason, 'Cancelamento'),
            p_user_id
        );
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'sale_id', p_sale_id,
        'status', 'CANCELED'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 15. FUNÇÃO RPC: EXCLUIR USUÁRIO COM SEGURANÇA
CREATE OR REPLACE FUNCTION public.delete_user_by_admin(
    p_user_id UUID
)
RETURNS JSONB AS $$
BEGIN
    DELETE FROM public.profiles WHERE id = p_user_id;
    DELETE FROM auth.users WHERE id = p_user_id;

    RETURN jsonb_build_object(
        'success', true,
        'deleted_user_id', p_user_id
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

