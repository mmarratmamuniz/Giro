-- 1. TABELA DE CATEGORIAS
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABELA DE PRODUTOS
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT,
    cost_price NUMERIC(10, 2) DEFAULT 0.00 NOT NULL,
    sale_price NUMERIC(10, 2) NOT NULL,
    stock_quantity INTEGER DEFAULT 0 NOT NULL,
    min_stock INTEGER DEFAULT 5 NOT NULL,
    unit TEXT DEFAULT 'un' NOT NULL,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABELA DE COMPRAS (SUPRIMENTOS / ENTRADAS)
CREATE TABLE IF NOT EXISTS public.purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL,
    supplier TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. ITENS DA COMPRA
CREATE TABLE IF NOT EXISTS public.purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT REFERENCES public.purchases(id) ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE RESTRICT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_cost NUMERIC(10, 2) NOT NULL
);

-- 5. TABELA DE VENDAS
CREATE TABLE IF NOT EXISTS public.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL,
    payment_method TEXT NOT NULL, -- 'Dinheiro', 'Pix', 'Crédito', 'Débito'
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. ITENS DA VENDA
CREATE TABLE IF NOT EXISTS public.sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT REFERENCES public.sales(id) ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE RESTRICT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL
);

-- 7. TABELA DE MOVIMENTAÇÕES DE ESTOQUE
CREATE TABLE IF NOT EXISTS public.stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE NOT NULL,
    movement_type TEXT NOT NULL, -- 'IN' ou 'OUT'
    quantity INTEGER NOT NULL,
    origin TEXT NOT NULL,        -- 'SALE', 'PURCHASE', 'MANUAL'
    note TEXT,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 8. TABELA DE PERFIS DE USUÁRIOS
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT,
    full_name TEXT,
    role TEXT DEFAULT 'operator' NOT NULL, -- 'admin' ou 'operator'
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 9. FUNÇÃO E TRIGGER PARA CRIAR PERFIL AUTOMATICAMENTE AO REGISTRAR USUÁRIO
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, full_name, role)
    VALUES (
        new.id,
        new.email,
        COALESCE(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
        COALESCE(new.raw_user_meta_data->>'role', 'admin')
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- 10. FUNÇÃO RPC PARA FINALIZAR VENDA ATOMICAMENTE (GARANTE BAIXA DE ESTOQUE E REGISTRO)
CREATE OR REPLACE FUNCTION public.create_complete_sale(
    p_payment_method TEXT,
    p_items JSONB,
    p_user_id UUID DEFAULT NULL
)
RETURNS JSONB AS $$
DECLARE
    v_sale_id BIGINT;
    v_total_amount NUMERIC(10, 2) := 0;
    v_item JSONB;
    v_product RECORD;
    v_qty INTEGER;
    v_price NUMERIC(10, 2);
BEGIN
    -- 1. Validar estoque e calcular total
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_qty := (v_item->>'quantity')::INTEGER;
        
        SELECT id, name, sale_price, stock_quantity, is_active
        INTO v_product
        FROM public.products
        WHERE id = (v_item->>'product_id')::BIGINT;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Produto ID % não encontrado.', (v_item->>'product_id');
        END IF;

        IF NOT v_product.is_active THEN
            RAISE EXCEPTION 'O produto "%" está inativo.', v_product.name;
        END IF;

        IF v_product.stock_quantity < v_qty THEN
            RAISE EXCEPTION 'Estoque insuficiente para "%". Disponível: %, Solicitado: %', 
                v_product.name, v_product.stock_quantity, v_qty;
        END IF;

        v_price := v_product.sale_price;
        v_total_amount := v_total_amount + (v_qty * v_price);
    END LOOP;

    -- 2. Criar registro da venda
    INSERT INTO public.sales (total_amount, payment_method, user_id)
    VALUES (v_total_amount, p_payment_method, p_user_id)
    RETURNING id INTO v_sale_id;

    -- 3. Inserir itens da venda e dar baixa no estoque com log
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_qty := (v_item->>'quantity')::INTEGER;

        SELECT sale_price INTO v_price
        FROM public.products
        WHERE id = (v_item->>'product_id')::BIGINT;

        INSERT INTO public.sale_items (sale_id, product_id, quantity, unit_price)
        VALUES (v_sale_id, (v_item->>'product_id')::BIGINT, v_qty, v_price);

        -- Decrementar estoque
        UPDATE public.products
        SET stock_quantity = stock_quantity - v_qty,
            updated_at = timezone('utc'::text, now())
        WHERE id = (v_item->>'product_id')::BIGINT;

        -- Registrar movimentação
        INSERT INTO public.stock_movements (product_id, movement_type, quantity, origin, note, user_id)
        VALUES (
            (v_item->>'product_id')::BIGINT,
            'OUT',
            v_qty,
            'SALE',
            'Venda #' || v_sale_id,
            p_user_id
        );
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'sale_id', v_sale_id,
        'total_amount', v_total_amount
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

