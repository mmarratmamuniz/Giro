-- 1. TABELA DE TURNOS DE CAIXA (ABERTURA E FECHAMENTO)
CREATE TABLE IF NOT EXISTS public.cash_shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    opened_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    closed_at TIMESTAMP WITH TIME ZONE,
    initial_amount NUMERIC(10, 2) DEFAULT 0.00 NOT NULL,
    final_amount NUMERIC(10, 2),        -- Valor informado na contagem física da gaveta
    system_amount NUMERIC(10, 2),       -- Valor calculado pelo sistema
    difference NUMERIC(10, 2),          -- Sobra (+) ou Falta (-)
    status TEXT DEFAULT 'OPEN' NOT NULL, -- 'OPEN' ou 'CLOSED'
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABELA DE TRANSAÇÕES DE CAIXA (SANGRIAS E SUPRIMENTOS)
CREATE TABLE IF NOT EXISTS public.cash_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT REFERENCES public.cash_shifts(id) ON DELETE CASCADE NOT NULL,
    type TEXT NOT NULL,                  -- 'SANGRIA' (Retirada) ou 'SUPRIMENTO' (Entrada de Troco)
    amount NUMERIC(10, 2) NOT NULL,
    reason TEXT NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. ADICIONAR COLUNAS NA TABELA DE VENDAS
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'COMPLETED' NOT NULL;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS discount_amount NUMERIC(10, 2) DEFAULT 0.00 NOT NULL;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS shift_id BIGINT REFERENCES public.cash_shifts(id) ON DELETE SET NULL;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS cancel_reason TEXT;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS canceled_at TIMESTAMP WITH TIME ZONE;

-- 4. HABILITAR RLS NAS NOVAS TABELAS
ALTER TABLE public.cash_shifts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cash_transactions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Acesso completo a turnos de caixa" ON public.cash_shifts FOR ALL USING (true);
CREATE POLICY "Acesso completo a transacoes de caixa" ON public.cash_transactions FOR ALL USING (true);

-- 5. ATUALIZAR FUNÇÃO RPC PARA FINALIZAR VENDA COM DESCONTO E VÍNCULO DE CAIXA
CREATE OR REPLACE FUNCTION public.create_complete_sale(
    p_payment_method TEXT,
    p_items JSONB,
    p_user_id UUID DEFAULT NULL,
    p_discount_amount NUMERIC DEFAULT 0.00,
    p_shift_id BIGINT DEFAULT NULL
)
RETURNS JSONB AS $$
DECLARE
    v_sale_id BIGINT;
    v_gross_amount NUMERIC(10, 2) := 0;
    v_net_amount NUMERIC(10, 2) := 0;
    v_item JSONB;
    v_product RECORD;
    v_qty INTEGER;
    v_price NUMERIC(10, 2);
BEGIN
    -- 1. Validar estoque e calcular total bruto
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_qty := (v_item->>'quantity')::INTEGER;
        
        SELECT id, name, sale_price, stock_quantity, is_active
        INTO v_product
        FROM public.products
        WHERE id = (v_item->>'product_id')::BIGINT;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Produto ID % não encontrado.', (v_item->>'product_id');
        END IF;

        IF NOT v_product.is_active THEN
            RAISE EXCEPTION 'O produto "%" está inativo.', v_product.name;
        END IF;

        IF v_product.stock_quantity < v_qty THEN
            RAISE EXCEPTION 'Estoque insuficiente para "%". Disponível: %, Solicitado: %', 
                v_product.name, v_product.stock_quantity, v_qty;
        END IF;

        v_price := v_product.sale_price;
        v_gross_amount := v_gross_amount + (v_qty * v_price);
    END LOOP;

    -- Calcular valor líquido após desconto
    v_net_amount := GREATEST(0, v_gross_amount - COALESCE(p_discount_amount, 0.00));

    -- 2. Criar registro da venda
    INSERT INTO public.sales (total_amount, payment_method, user_id, status, discount_amount, shift_id)
    VALUES (v_net_amount, p_payment_method, p_user_id, 'COMPLETED', COALESCE(p_discount_amount, 0.00), p_shift_id)
    RETURNING id INTO v_sale_id;

    -- 3. Inserir itens da venda e dar baixa no estoque com log
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_qty := (v_item->>'quantity')::INTEGER;

        SELECT sale_price INTO v_price
        FROM public.products
        WHERE id = (v_item->>'product_id')::BIGINT;

        INSERT INTO public.sale_items (sale_id, product_id, quantity, unit_price)
        VALUES (v_sale_id, (v_item->>'product_id')::BIGINT, v_qty, v_price);

        -- Decrementar estoque
        UPDATE public.products
        SET stock_quantity = stock_quantity - v_qty,
            updated_at = timezone('utc'::text, now())
        WHERE id = (v_item->>'product_id')::BIGINT;

        -- Registrar movimentação
        INSERT INTO public.stock_movements (product_id, movement_type, quantity, origin, note, user_id)
        VALUES (
            (v_item->>'product_id')::BIGINT,
            'OUT',
            v_qty,
            'SALE',
            'Venda #' || v_sale_id,
            p_user_id
        );
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'sale_id', v_sale_id,
        'gross_amount', v_gross_amount,
        'discount_amount', p_discount_amount,
        'total_amount', v_net_amount
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 6. FUNÇÃO RPC PARA CANCELAR/ESTORNAR VENDA (DEVOLVE ESTOQUE ATOMICAMENTE)
CREATE OR REPLACE FUNCTION public.cancel_sale(
    p_sale_id BIGINT,
    p_reason TEXT,
    p_user_id UUID DEFAULT NULL
)
RETURNS JSONB AS $$
DECLARE
    v_sale RECORD;
    v_item RECORD;
BEGIN
    -- 1. Buscar a venda
    SELECT * INTO v_sale FROM public.sales WHERE id = p_sale_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Venda #% não encontrada.', p_sale_id;
    END IF;

    IF v_sale.status = 'CANCELED' THEN
        RAISE EXCEPTION 'A venda #% já foi cancelada anteriormente.', p_sale_id;
    END IF;

    -- 2. Atualizar status da venda
    UPDATE public.sales
    SET status = 'CANCELED',
        cancel_reason = p_reason,
        canceled_at = timezone('utc'::text, now())
    WHERE id = p_sale_id;

    -- 3. Devolver cada item para o estoque e registrar movimentação
    FOR v_item IN SELECT * FROM public.sale_items WHERE sale_id = p_sale_id
    LOOP
        UPDATE public.products
        SET stock_quantity = stock_quantity + v_item.quantity,
            updated_at = timezone('utc'::text, now())
        WHERE id = v_item.product_id;

        INSERT INTO public.stock_movements (product_id, movement_type, quantity, origin, note, user_id)
        VALUES (
            v_item.product_id,
            'IN',
            v_item.quantity,
            'SALE_CANCEL',
            'Estorno da Venda #' || p_sale_id || ' - Motivo: ' || COALESCE(p_reason, 'Cancelamento'),
            p_user_id
        );
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'sale_id', p_sale_id,
        'status', 'CANCELED'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
